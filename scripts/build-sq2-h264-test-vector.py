#!/usr/bin/env python3
"""Build a small pinned H264 test clip and its software-decoded reference.

Encodes ffmpeg testsrc2 (320x240, 6 frames, constrained-baseline, no B frames,
AUD per access unit, single thread) to Annex-B, splits it into access units,
decodes the same file with ffmpeg to NV12 and writes a C header containing the
bitstream, access-unit offsets and per-frame zlib-compatible CRC32 of the
visible Y and interleaved UV planes. Bit-exact H264 decoders must match.
Host-only; never contacts a device.
"""
import argparse
import hashlib
import json
import subprocess
import sys
import zlib
from pathlib import Path

W, H, FRAMES = 320, 240, 6


def run(cmd):
    subprocess.run(cmd, check=True, stdout=subprocess.DEVNULL, stderr=subprocess.PIPE)


def nal_units(data):
    """Yield (start_of_startcode, nal_type) for Annex-B data."""
    i, n = 0, len(data)
    while i + 3 <= n:
        if data[i:i + 3] == b'\0\0\1':
            start = i - 1 if i and data[i - 1] == 0 else i
            if i + 3 < n:
                yield start, data[i + 3] & 0x1f
            i += 3
        else:
            i += 1


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--out', type=Path, required=True, help='new directory')
    a = ap.parse_args()
    a.out.mkdir(parents=False, exist_ok=False)
    clip, ref = a.out / 'clip.h264', a.out / 'ref.nv12'
    run(['ffmpeg', '-nostdin', '-hide_banner', '-f', 'lavfi', '-i',
         f'testsrc2=size={W}x{H}:rate=30', '-frames:v', str(FRAMES),
         '-c:v', 'libx264', '-profile:v', 'baseline', '-pix_fmt', 'yuv420p',
         '-g', str(FRAMES), '-bf', '0', '-threads', '1',
         '-x264-params', f'aud=1:keyint={FRAMES}:sliced-threads=0',
         '-f', 'h264', str(clip)])
    run(['ffmpeg', '-nostdin', '-hide_banner', '-threads', '1', '-i', str(clip),
         '-f', 'rawvideo', '-pix_fmt', 'nv12', str(ref)])
    data, raw = clip.read_bytes(), ref.read_bytes()
    aus = [s for s, t in nal_units(data) if t == 9]
    if len(aus) != FRAMES or aus[0] != 0:
        sys.exit(f'expected {FRAMES} AUD-delimited access units, got {len(aus)}')
    bounds = aus + [len(data)]
    frame = W * H * 3 // 2
    if len(raw) != frame * FRAMES:
        sys.exit('reference size mismatch')
    crcs = []
    for f in range(FRAMES):
        y = raw[f * frame:f * frame + W * H]
        uv = raw[f * frame + W * H:(f + 1) * frame]
        crcs.append((zlib.crc32(y), zlib.crc32(uv), y[:16].hex(), uv[:16].hex()))
    lines = ['/* Generated by scripts/build-sq2-h264-test-vector.py; do not edit. */',
             f'#define SQ2_VEC_W {W}', f'#define SQ2_VEC_H {H}',
             f'#define SQ2_VEC_FRAMES {FRAMES}',
             f'#define SQ2_VEC_SHA256 "{hashlib.sha256(data).hexdigest()}"',
             'static const u32 sq2_vec_au[SQ2_VEC_FRAMES + 1] = { ' +
             ', '.join(str(b) for b in bounds) + ' };',
             'static const u32 sq2_vec_crc_y[SQ2_VEC_FRAMES] = { ' +
             ', '.join(f'0x{c[0]:08x}' for c in crcs) + ' };',
             'static const u32 sq2_vec_crc_uv[SQ2_VEC_FRAMES] = { ' +
             ', '.join(f'0x{c[1]:08x}' for c in crcs) + ' };',
             f'static const u8 sq2_vec_stream[{len(data)}] = {{']
    for i in range(0, len(data), 16):
        lines.append(' ' + ', '.join(f'0x{b:02x}' for b in data[i:i + 16]) + ',')
    lines.append('};')
    (a.out / 'sq2-h264-vector.h').write_text('\n'.join(lines) + '\n')
    meta = {'width': W, 'height': H, 'frames': FRAMES, 'bytes': len(data),
            'stream_sha256': hashlib.sha256(data).hexdigest(),
            'reference_sha256': hashlib.sha256(raw).hexdigest(),
            'access_units': bounds,
            'frames_detail': [{'crc_y': f'{c[0]:08x}', 'crc_uv': f'{c[1]:08x}',
                               'y_head': c[2], 'uv_head': c[3]} for c in crcs],
            'ffmpeg': subprocess.run(['ffmpeg', '-version'], capture_output=True,
                                     text=True).stdout.splitlines()[0]}
    (a.out / 'vector.json').write_text(json.dumps(meta, indent=1) + '\n')
    print(json.dumps({k: meta[k] for k in ('bytes', 'stream_sha256', 'access_units')}))
    for i, d in enumerate(meta['frames_detail']):
        print(i, d['crc_y'], d['crc_uv'], d['y_head'])


if __name__ == '__main__':
    main()
